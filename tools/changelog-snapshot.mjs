/**
 * Bake the release history into docs/changelog.html.
 *
 *   node tools/changelog-snapshot.mjs
 *
 * The page renders itself from the GitHub Releases API, which is the right
 * source — releases are written there and nowhere else, so the page cannot drift
 * out of date. But a crawler does not run the script, and neither does a reader
 * with JavaScript off or an hourly API limit already spent: all three get a
 * paragraph reading "Loading from GitHub", on a page that carries a canonical
 * link and invites indexing. A release history nobody can read is a thin page,
 * and it is one of the few pages on this site with a reason to rank.
 *
 * So the same list is written into the HTML as well. `assets/github.js` replaces
 * it wholesale on load — it already sets `innerHTML = ''` before rendering — so
 * a reader with a working network never sees this copy, and it going stale costs
 * nothing but a crawler reading an older list than the one a person sees. Run
 * this after tagging.
 *
 * Release notes are inserted as TEXT, never as HTML. They are Markdown written
 * by a person and fetched over the network, and the live renderer treats them
 * the same way for the same reason.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const page = join(here, '..', 'docs', 'changelog.html');

const OPEN = '<!-- RELEASES:BEGIN — generated by tools/changelog-snapshot.mjs -->';
const CLOSE = '<!-- RELEASES:END -->';

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

// The whole JSON, filtered here rather than with `gh -q`. A jq expression has to
// survive the shell, and on Windows `shell: true` splits it on the spaces inside
// the braces and reports the first field as a command that does not exist.
const r = spawnSync('gh', ['api', 'repos/Wasabules/SnmpLens/releases?per_page=20'], {
  encoding: 'utf8',
  shell: process.platform === 'win32',
  maxBuffer: 8 << 20,
});

if (r.status !== 0) {
  console.error('gh could not read the releases:\n' + (r.stderr || '').trim());
  process.exit(1);
}

const releases = JSON.parse(r.stdout).map((x) => ({
  tag: x.tag_name, name: x.name, at: x.published_at,
  body: x.body, pre: x.prerelease, url: x.html_url,
}));
if (!releases.length) {
  console.error('No releases came back; the page was left alone.');
  process.exit(1);
}

const html = releases.map((rel) => {
  const date = rel.at ? rel.at.slice(0, 10) : '';
  const body = (rel.body || '').trim();
  // Markdown, rendered as the plain text it is. The live version does the same;
  // pretending to parse it here would put two different renderings of the same
  // note on the same page depending on whether the network answered.
  const notes = body
    ? `<pre class="release-notes no-copy">${esc(body)}</pre>`
    : '<p class="muted small">No notes were written for this release.</p>';
  return `      <section class="release-entry">
        <div class="release-head">
          <h2><a href="${esc(rel.url)}">${esc(rel.name || rel.tag)}</a></h2>
          <time datetime="${esc(rel.at)}">${esc(date)}</time>
          ${rel.pre ? '<span class="badge">pre-release</span>' : ''}
        </div>
        ${notes}
      </section>`;
}).join('\n');

const block = `${OPEN}
${html}
      <p class="muted small">
        This list is a snapshot, written into the page so that it can be read without
        scripts. With a working network it is replaced by the live one from
        <a href="https://github.com/Wasabules/SnmpLens/releases">GitHub Releases</a>.
      </p>
      ${CLOSE}`;

let s = readFileSync(page, 'utf8');
const host = '<div style="margin-top:2.5rem" data-gh="releases">';
const i = s.indexOf(host);
if (i < 0) {
  console.error('The releases host is no longer in changelog.html.');
  process.exit(1);
}

if (s.includes(OPEN)) {
  s = s.slice(0, s.indexOf(OPEN)) + block + s.slice(s.indexOf(CLOSE) + CLOSE.length);
} else {
  const end = s.indexOf('</div>', i);
  s = s.slice(0, i + host.length) + '\n' + block + '\n    ' + s.slice(end);
}

writeFileSync(page, s);
console.log(`Wrote ${releases.length} releases into docs/changelog.html.`);
